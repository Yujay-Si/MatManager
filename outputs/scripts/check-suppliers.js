'use strict';
const assert = require('node:assert/strict');
require('../preview-site/material-domain.js');
const D = global.MaterialDomain;
let state = D.save(D.empty(), 'suppliers', { id: 's', name: '老供应商', openingDate: '2026-10-01', openingAmount: '100' });
assert.equal(D.supplierBalance(state, 's', '2026-10-08'), 10000);
assert.equal(D.supplierBalance(state, 's', '2026-09-30'), null);
state = D.save(state, 'orders', { id: 'o', supplierId: 's', date: '2026-10-02', note: '', lines: [{ id: 'l', material: '201', spec: '600', quantity: 10, price: '5', product: '', note: '' }] });
state = D.save(state, 'receipts', { id: 'r', supplierId: 's', date: '2026-10-03', note: '', lines: [{ id: 'rl', material: '201', spec: '600', quantity: 2, price: '5', weights: ['10'], orderId: 'o', orderLineId: 'l', progress: '' }] });
state = D.save(state, 'suppliers', { ...state.suppliers[0], contact: '张师傅', phone: '13800138000', address: '厂区1号', note: '月结', active: false });
assert.equal(D.supplierBalance(state, 's', '2026-10-02'), 10000);
assert.equal(D.supplierBalance(state, 's', '2026-10-03'), 15000);
assert.equal(D.remaining(state, 'o', 'l'), 8);
assert.throws(() => D.save(state, 'orders', { ...state.orders[0], id: 'new-order' }), /停用/);
assert.throws(() => D.save(state, 'payments', { id: 'p', supplierId: 's', date: '2026-10-04', repayment: '10', discount: '0', note: '' }), /停用/);
state = D.save(state, 'receipts', { ...state.receipts[0], note: '更正旧单' });
assert.equal(state.receipts[0].note, '更正旧单');
assert.throws(() => D.save(state, 'suppliers', { ...state.suppliers[0], active: 'false' }), /状态/);
assert.throws(() => D.save(state, 'suppliers', { ...state.suppliers[0], phone: 'x'.repeat(501) }), /电话/);
const restored = D.merge(D.empty(), { format: 'material-management', version: 1, state });
assert.equal(restored.suppliers[0].phone, '13800138000');
assert.equal(restored.suppliers[0].active, false);
state = D.save(state, 'suppliers', { ...state.suppliers[0], active: true });
state = D.save(state, 'payments', { id: 'p', supplierId: 's', date: '2026-10-04', repayment: '10', discount: '0', note: '' });
assert.equal(D.supplierBalance(state, 's', '2026-10-08'), 14000);
console.log('供应商验证通过：旧资料兼容、扩展字段、截至日期余额、停用拒绝新单、历史编辑、启用与备份。');
